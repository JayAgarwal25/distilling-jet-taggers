"""Reference files: every model, recipe and run of the paper with its exact settings.

`python -m jetkd.reference` writes configs/models.yaml, configs/recipes.yaml and
configs/RUNS.md; with `--summary results/summary.json` the runs also get their test metrics.
"""

from __future__ import annotations

import argparse
import inspect
import json
from dataclasses import asdict
from functools import partial
from pathlib import Path

import yaml

from jetkd.distillation import KDConfig
from jetkd.models import MODELS, build
from jetkd.recipes import RECIPES, recipe_for
from jetkd.study import paper_runs


def model_settings(name: str) -> dict:
    """The class and every constructor argument of a model, defaults included."""
    entry = MODELS[name]
    cls, given = (entry.func, entry.keywords) if isinstance(entry, partial) else (entry, {})
    defaults = {}
    for c in (getattr(cls, "net_class", None), cls):   # the inner network's settings too
        if c is not None:
            defaults.update({k: p.default for k, p in inspect.signature(c).parameters.items()
                             if p.default is not inspect.Parameter.empty})
    args = {k: list(v) if isinstance(v, tuple) else v for k, v in {**defaults, **given}.items()}
    return {"class": f"{cls.__module__}.{cls.__name__}", "arguments": args,
            "parameters": sum(p.numel() for p in build(name).parameters()),
            "recipe": recipe_for(name).name}


def models_yaml() -> str:
    return yaml.safe_dump({n: model_settings(n) for n in MODELS}, sort_keys=False, width=100)


def recipes_yaml() -> str:
    return yaml.safe_dump({n: r.as_record() for n, r in RECIPES.items()}, sort_keys=False, width=100)


def runs_md(summary: dict | None = None) -> str:
    models = {n: model_settings(n) for n in MODELS}
    out = ["# Runs", "",
           "Generated by `python -m jetkd.reference`. Every model, recipe and run of the paper.", "",
           "## Models", "", "| model | class | settings | parameters | recipe |", "|---|---|---|---|---|"]
    for n, m in models.items():
        args = ", ".join(f"{k}={v}" for k, v in m["arguments"].items())
        out.append(f"| `{n}` | `{m['class'].rsplit('.', 1)[1]}` | {args} | {m['parameters']:,} "
                   f"| `{m['recipe']}` |")
    out += ["", "## Recipes", "", "Counts are iterations. Biases get no weight decay.", "",
            "| recipe | optimizer | lr | weight decay | schedule | batch | iterations | validate every | source |",
            "|---|---|---|---|---|---|---|---|---|"]
    for r in RECIPES.values():
        out.append(f"| `{r.name}` | {r.optimizer} | {r.lr:g} | {r.weight_decay:g} | {r.scheduler} "
                   f"| {r.batch_size} | {r.iterations:,} | {r.validate_every:,} | `{r.source}` |")
    kd = asdict(KDConfig())
    out += ["", "## Distillation", "",
            f"alpha = {kd['alpha']}, T = {kd['temperature']} for every distilled run "
            "(`jetkd/distillation.py`). Gradients are clipped at norm 1; the checkpoint with the "
            "lowest validation BCE is kept.", "",
            "The teacher `lgatr_slim_ens` is the mean logit of the three `lgatr_slim` runs; its "
            "teacher seed 1001 only labels it.", "", "## Runs", ""]
    metrics = (summary or {}).get("runs", {})
    head = "| run | model | teacher | teacher seed | seed | recipe |"
    if metrics:
        head += " AUC | rej@0.5 | rej@0.3 |"
    out += [head, "|" + "---|" * (head.count("|") - 1)]
    for r in paper_runs():
        row = (f"| `{r.id}` | `{r.student}` | {r.teacher or 'none'} | {r.teacher_seed or ''} "
               f"| {r.seed} | `{r.recipe}` |")
        if metrics:
            m = metrics.get(r.id)
            row += (f" {m['auc']:.5f} | {m['rej50']:.0f} | {m['rej30']:.0f} |" if m else " | | |")
        out.append(row)
    return "\n".join(out) + "\n"


def files(summary: dict | None = None) -> dict[str, str]:
    return {"configs/models.yaml": models_yaml(), "configs/recipes.yaml": recipes_yaml(),
            "configs/RUNS.md": runs_md(summary)}


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--summary", help="results/summary.json, for the test metrics of each run")
    ap.add_argument("--check", action="store_true", help="fail if a file is out of date")
    args = ap.parse_args()
    summary = json.loads(Path(args.summary).read_text()) if args.summary else None
    for path, text in files(summary).items():
        if args.check:
            if Path(path).read_text() != text:
                raise SystemExit(f"{path} is out of date")
        else:
            Path(path).parent.mkdir(parents=True, exist_ok=True)
            Path(path).write_text(text)
