"""Every training run in the paper. `python -m jetkd.study` writes configs/runs.yaml.

Run ids are `<student>__scratch__s<seed>` or `<student>__kd_<teacher>_t<teacher seed>__s<seed>`.
"""

from __future__ import annotations

import argparse
from dataclasses import dataclass
from pathlib import Path

import yaml

from jetkd.recipes import recipe_for

SEEDS = (1001, 1002, 1003)
TEACHERS = ("part", "mipart", "lgatr", "lgatr_slim", "omnilearned_s", "part_pretrained")
PAIRED_TEACHERS = ("part", "lgatr", "lgatr_slim")   # teacher seed = student seed; others 1001
SCALING_TEACHERS = ("lgatr", "part_pretrained", "omnilearned_s")

MATRIX_STUDENTS = (
    "transformer_200k", "part_200k", "mipart_200k", "lgatr_slim_200k", "lorentznet_200k",
)
WIDTH_STUDENTS = tuple(f"{f}_deep_{s}" for f in ("transformer", "lgatr_slim")
                       for s in ("200k", "20k", "2k"))
# block counts of the depth studies, and the block count of the matrix student
DEPTHS = {
    "transformer_200k": ((0, 1, 2, 3, 4, 6, 8, 10), 10),
    "lgatr_slim_200k": ((1, 2, 3, 4, 5, 6, 8, 10), 5),
}


@dataclass(frozen=True)
class Run:
    student: str
    teacher: str | None
    teacher_seed: int | None
    seed: int
    recipe: str
    tables: tuple[str, ...]

    @property
    def id(self) -> str:
        arm = f"kd_{self.teacher}_t{self.teacher_seed}" if self.teacher else "scratch"
        return f"{self.student}__{arm}__s{self.seed}"


def paper_runs() -> list[Run]:
    """All runs, each with the paper tables that read it."""
    tables: dict[tuple, set[str]] = {}

    def use(student, seed, teacher, names):
        ts = (seed if teacher in PAIRED_TEACHERS else 1001) if teacher else None
        tables.setdefault((student, teacher, ts, seed), set()).update(names)

    matrix = {"matrix_auc", "matrix_rej", "gains", "complete"}
    for st in MATRIX_STUDENTS:
        for seed in SEEDS:
            use(st, seed, None, matrix | {"students", "cost_provisional"})
            for t in TEACHERS:
                extra = set()
                if t == "part_pretrained":
                    extra = {"cost_provisional"}
                    if st in ("transformer_200k", "lgatr_slim_200k"):
                        extra.add("benyas")
                use(st, seed, t, matrix | extra)

    for st in WIDTH_STUDENTS:
        for seed in SEEDS:
            use(st, seed, None, {"size_full", "size", "cost_provisional"})
            for t in SCALING_TEACHERS:
                extra = {"size", "cost_provisional", "benyas"} if t == "part_pretrained" else set()
                use(st, seed, t, {"size_full"} | extra)

    for base, (depths, own) in DEPTHS.items():
        table = "depth_transformer" if base == "transformer_200k" else "depth_slim"
        for n in depths:
            st = base if n == own else f"{base}_L{n}"
            use(st, 1001, None, {table, "depth"})
            for t in SCALING_TEACHERS:
                use(st, 1001, t, {table, "depth"} if t == "part_pretrained" else {table})

    return [Run(st, t, ts, seed, recipe_for(st).name, tuple(sorted(names)))
            for (st, t, ts, seed), names in tables.items()]


def dump(runs: list[Run]) -> str:
    rows = [{"id": r.id, "student": r.student, "teacher": r.teacher,
             "teacher_seed": r.teacher_seed, "seed": r.seed, "recipe": r.recipe,
             "tables": list(r.tables)} for r in runs]
    return ("# generated by `python -m jetkd.study`\n"
            + yaml.safe_dump({"runs": rows}, sort_keys=False, default_flow_style=None, width=100))


def load(path) -> list[Run]:
    rows = yaml.safe_load(Path(path).read_text())["runs"]
    return [Run(r["student"], r["teacher"], r["teacher_seed"], r["seed"], r["recipe"],
                tuple(r["tables"])) for r in rows]


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("path", nargs="?", default="configs/runs.yaml")
    ap.add_argument("--check", action="store_true", help="fail if the file is out of date")
    args = ap.parse_args()
    text = dump(paper_runs())
    if args.check:
        raise SystemExit(0 if Path(args.path).read_text() == text else f"{args.path} is out of date")
    Path(args.path).write_text(text)
